/**
 * Escapes a string for safe insertion as HTML text content.
 * Prevents XSS when using innerHTML with user-supplied data.
 * @param {string} str
 * @returns {string}
 */
export function escapeHtml(str) {
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}
